public class CartaIdentita {
    public static void main(String[] args) throws Exception {
    
    String nome;
    nome = "Alessio";
    System.out.println("Nome = "+ nome);

    String cognome;
    cognome = "Galvagni";
    System.out.println("Cognome = "+ cognome);

    String inizialeDelCognome;
    inizialeDelCognome = "G";
    System.out.println("Iniziale del cognome: " + inizialeDelCognome);

    String Annodinascita;
    Annodinascita = "2010";
    System.out.println("Anno di nascita: " + Annodinascita);

    String Eta2026;
    Eta2026 = "16";
    System.out.println("Età compiuta nel 2026: " + Eta2026);

    String Altezza;
    Altezza = "1.83";
    System.out.println("Altezza: " + Altezza);

    boolean corsoinformatica;
    corsoinformatica = true;
    System.out.println("Corso di informatica: " + corsoinformatica);
    }
}
