public class ConversioneSecondi {
    public static void main(String[] args) throws Exception {

        int secondi;
        secondi = 7325;
        System.out.println("Secondi: " + secondi);

        int minuti;
        minuti = secondi / 60;
        System.out.println("Minuti: " + minuti);

        int ore;
        ore = minuti / 60;
        System.out.println("Ore: " + ore);
        
    }
}